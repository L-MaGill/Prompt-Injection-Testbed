-- Design notes for the injection testbed:
--   - CUSTOMER_NOTES, SELLER_NOTES, PRODUCT_DESCRIPT, LINE_NOTES, and
--     RESTORATION_HISTORY are free-text fields. These are the columns
--     we'll later use to stage INDIRECT injection payloads -- text an
--     "employee" typed in that the chatbot reads back later as data,
--     not as part of the user's own message.
--   - Everything else is normal structured data (dates, flags, numbers)
--     and isn't useful for hiding instructions in.

PRAGMA foreign_keys = ON;

-- Supertype: every person is a customer and/or a seller (not mutually exclusive)
CREATE TABLE PERSON (
    PERSON_ID       INTEGER PRIMARY KEY,
    PERSON_FNAME    VARCHAR(20),
    PERSON_LNAME    VARCHAR(20),
    PERSON_P_NUMBER VARCHAR(15),
    PERSON_EMAIL    VARCHAR(100),
    IS_CUSTOMER     TINYINT(1) DEFAULT 0,
    IS_SELLER       TINYINT(1) DEFAULT 0
);

CREATE TABLE CUSTOMER (
    PERSON_ID               INTEGER PRIMARY KEY,
    CUSTOMER_SINCE          DATE,
    PREFERRED_CONTACT_METHOD VARCHAR(50),
    ACTIVE_CUSTOMER_FLAG    TINYINT(1),
    PREFERRED_PAYMENT_METHOD VARCHAR(50),
    CUSTOMER_NOTES          VARCHAR(500),   -- free text: injection staging ground
    FOREIGN KEY (PERSON_ID) REFERENCES PERSON(PERSON_ID)
);

CREATE TABLE SELLER (
    PERSON_ID           INTEGER PRIMARY KEY,
    SELLER_SINCE         DATE,
    GOVERNMENT_ID_TYPE    VARCHAR(50) NOT NULL,
    GOVERNMENT_ID_NUMBER  VARCHAR(50) NOT NULL,
    ID_VERIFIED_FLAG      TINYINT(1),
    SELLER_NOTES          VARCHAR(500),  -- free text: injection staging ground
    FOREIGN KEY (PERSON_ID) REFERENCES PERSON(PERSON_ID)
);

CREATE TABLE EMPLOYEE (
    EMP_ID           INTEGER PRIMARY KEY,
    EMP_FNAME        VARCHAR(20),
    EMP_LNAME        VARCHAR(20),
    EMP_AGE          INTEGER,
    EMP_PHONE_NUMBER VARCHAR(13),
    EMP_WAGE         DECIMAL(6,2),
    EMP_HOME_ADDRESS VARCHAR(50)
);

CREATE TABLE EMPLOYEE_HISTORY (
    EMP_HISTORY_ID         INTEGER PRIMARY KEY,
    EMP_ID                 INTEGER NOT NULL,
    EMP_HIRE_DATE          DATE,
    EMP_NOTES              VARCHAR(400),
    EMP_LEAVE_DATE         DATE,
    EMP_EMPLOYMENT_MONTHS  INTEGER,
    FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEE(EMP_ID)
);

-- Supertype: overlapping/partial -- a product can be none, one, or (rarely) more subtypes
CREATE TABLE PRODUCT (
    PRODUCT_ID        INTEGER PRIMARY KEY,
    PRODUCT_DESCRIPT  VARCHAR(500),   -- free text: injection staging ground
    PRODUCT_CONDITION VARCHAR(10),
    ACQUIRED_PRICE    DECIMAL(8,2),
    IS_ELECTRONIC     TINYINT(1) DEFAULT 0,
    IS_COLLECTIBLE    TINYINT(1) DEFAULT 0,
    IS_JEWELRY        TINYINT(1) DEFAULT 0,
    IS_ANTIQUE        TINYINT(1) DEFAULT 0
);

CREATE TABLE ELECTRONICS (
    PRODUCT_ID         INTEGER PRIMARY KEY,
    WARRANTY_INCLUDED  TINYINT(1),
    DEVICE_TYPE        VARCHAR(15),
    POWER_REQUIREMENTS VARCHAR(15),
    STORAGE_CAPACITY   VARCHAR(5),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID)
);

CREATE TABLE COLLECTIBLES (
    PRODUCT_ID              INTEGER PRIMARY KEY,
    RELEASE_YEAR             INTEGER,
    CATEGORY                 VARCHAR(20),
    COLLECT_CONDITION        VARCHAR(20),
    AUTHENTICITY_CERTIFICATE TINYINT(1),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID)
);

CREATE TABLE JEWELRY (
    PRODUCT_ID   INTEGER PRIMARY KEY,
    MATERIAL     VARCHAR(20),
    JEWEL_TYPE   VARCHAR(20),
    CARAT_VALUE  INTEGER,
    WEIGHT_GRAMS VARCHAR(20),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID)
);

CREATE TABLE ANTIQUES (
    PRODUCT_ID          INTEGER PRIMARY KEY,
    ANTIQUE_YEAR_MADE    INTEGER,
    ANTIQUE_MAKER        VARCHAR(40),
    ANTIQUE_MATERIALS    VARCHAR(20),
    RESTORATION_HISTORY  VARCHAR(100),  -- free text: injection staging ground
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID)
);

CREATE TABLE INVENTORY (
    INV_ID       INTEGER PRIMARY KEY,
    PRODUCT_ID   INTEGER NOT NULL,
    INV_COUNT    INTEGER,
    INV_LOCATION VARCHAR(50),
    INV_STATUS   VARCHAR(50),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID)
);

CREATE TABLE INVOICE (
    INVOICE_ID    INTEGER PRIMARY KEY,
    PERSON_ID     INTEGER NOT NULL,
    EMP_ID        INTEGER NOT NULL,
    INVOICE_DATE  DATE NOT NULL,
    INVOICE_TOTAL DECIMAL(6,2) NOT NULL,
    PERSON_TYPE   VARCHAR(50) NOT NULL,  -- 'customer' or 'seller'
    FOREIGN KEY (PERSON_ID) REFERENCES PERSON(PERSON_ID),
    FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEE(EMP_ID)
);

CREATE TABLE INVOICE_LINE (
    INVOICE_LINE_ID INTEGER PRIMARY KEY,
    INVOICE_ID      INTEGER NOT NULL,
    PRODUCT_ID      INTEGER NOT NULL,
    SALE_PRICE      DECIMAL(8,2),
    LINE_NOTES      VARCHAR(300),   -- free text: injection staging ground
    QUANTITY        INTEGER,
    FOREIGN KEY (INVOICE_ID) REFERENCES INVOICE(INVOICE_ID),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID)
);

CREATE TABLE INVOICE_HISTORY (
    INVOICE_HISTORY_ID INTEGER PRIMARY KEY,
    INVOICE_ID          INTEGER NOT NULL,
    EMPLOYEE_UPDATE_ID   INTEGER NOT NULL,
    CHANGE_DATE          DATE,
    PREV_TOTAL           DECIMAL(6,2),
    NEW_TOTAL             DECIMAL(6,2),
    CHANGE_TYPE           CHAR(50),
    FOREIGN KEY (INVOICE_ID) REFERENCES INVOICE(INVOICE_ID),
    FOREIGN KEY (EMPLOYEE_UPDATE_ID) REFERENCES EMPLOYEE(EMP_ID)
);
